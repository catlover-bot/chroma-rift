#!/usr/bin/env node
'use strict';
/* global __dirname, Buffer */
// Rasterize the three Japanese destination plaques at authoring time. The
// checked-in bit masks are decoded into owned Three DataTextures at runtime;
// the app does not need a system font or a browser.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openBrowser, sha256 } = require('./lib/three-scene-qa.cjs');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/rendering/firstPerson/destinationSignData.ts');
const labels = { '02': '02 収蔵庫', '03': '03 映写室', '04': '04 鏡越しの回廊' };
const width = 256, height = 64;

async function main() {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'chroma-signs-'));
  fs.writeFileSync(path.join(temporary, 'index.html'), '<!doctype html><meta charset="utf-8">');
  const browser = await openBrowser(temporary);
  try {
    const masks = {};
    for (const [id, label] of Object.entries(labels)) {
      const encoded = await browser.evaluate(`(async () => {
        await document.fonts.load('28px "Noto Sans CJK JP"');
        const canvas = document.createElement('canvas');
        canvas.width = ${width}; canvas.height = ${height};
        const context = canvas.getContext('2d');
        let size = 30;
        do { context.font = size + 'px "Noto Sans CJK JP"'; size--; }
        while (context.measureText(${JSON.stringify(label)}).width > ${width - 18} && size > 19);
        context.fillStyle = '#fff';
        context.textAlign = 'center'; context.textBaseline = 'middle';
        context.fillText(${JSON.stringify(label)}, ${width / 2}, ${height / 2 + 1});
        const rgba = context.getImageData(0, 0, ${width}, ${height}).data;
        const bits = new Uint8Array(${width * height / 8});
        for (let i = 0; i < ${width * height}; i++)
          if (rgba[i * 4 + 3] >= 96) bits[i >> 3] |= 1 << (7 - i % 8);
        return btoa(String.fromCharCode(...bits));
      })()`);
      if (Buffer.from(encoded, 'base64').length !== width * height / 8)
        throw new Error(`${id}: incomplete sign mask`);
      masks[id] = encoded;
    }
    if (browser.errors.length) throw new Error(JSON.stringify(browser.errors));
    const source = `// Generated by scripts/generate-destination-signs.cjs from Noto Sans CJK JP.\n` +
      `// The font is not bundled; these are three monochrome sign masks.\n` +
      `export const DESTINATION_SIGN_WIDTH = ${width};\nexport const DESTINATION_SIGN_HEIGHT = ${height};\n` +
      `export const DESTINATION_SIGN_LABELS = ${JSON.stringify(labels, null, 2)} as const;\n` +
      `export type DestinationSignId = keyof typeof DESTINATION_SIGN_LABELS;\n` +
      `export const DESTINATION_SIGN_MASKS: Record<DestinationSignId, string> = ${JSON.stringify(masks, null, 2)};\n`;
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source)
        throw new Error('destinationSignData.ts differs from the generated signs');
    } else fs.writeFileSync(output, source);
    console.log(`destination signs ${sha256(Buffer.from(source))} (${Object.keys(masks).join(', ')})`);
  } finally {
    await browser.close();
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
